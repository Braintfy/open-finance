#!/usr/bin/env bash
# PURPOSE: Синхронизация source-файла MemPalace с текущей версией MEMORY.md.
# Запускается вручную после значимых изменений или автоматически через pre-push hook.

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCES_DIR="$HOME/.mempalace/sources/open-finance"

# Определение текущей версии
VERSION=$(grep -m1 -oE '^\## \[?[0-9]+\.[0-9]+\.[0-9]+\]?' "$PROJECT_ROOT/CHANGELOG.md" | head -1 | sed -E 's/[^0-9.]//g' || echo "unknown")

if [ "$VERSION" = "unknown" ]; then
  echo "[sync-mempalace] WARN: не удалось определить версию из CHANGELOG.md"
  VERSION=$(date +%Y%m%d)
fi

SNAPSHOT="$SOURCES_DIR/current-context-v${VERSION}.md"

# Если папки нет — создать
if [ ! -d "$SOURCES_DIR" ]; then
  echo "[sync-mempalace] создаю $SOURCES_DIR"
  mkdir -p "$SOURCES_DIR"
fi

# Удалить старые snapshots (оставить только текущий)
echo "[sync-mempalace] удаляю старые snapshots..."
find "$SOURCES_DIR" -maxdepth 1 -name 'current-context-v*.md' -not -name "current-context-v${VERSION}.md" -delete 2>/dev/null || true

# Собрать snapshot: MEMORY.md + git log + краткая stats
{
  echo "# Open Finance — context snapshot v${VERSION}"
  echo ""
  echo "> Auto-generated by \`./scripts/sync-mempalace.sh\` on $(date -u +'%Y-%m-%d %H:%M UTC')"
  echo "> Source: \`$PROJECT_ROOT\`"
  echo ""
  echo "## Recent commits"
  echo ""
  echo '```'
  (cd "$PROJECT_ROOT" && git log --oneline -30) 2>/dev/null || echo "(no git log)"
  echo '```'
  echo ""
  echo "---"
  echo ""
  cat "$PROJECT_ROOT/MEMORY.md"
} > "$SNAPSHOT"

LINES=$(wc -l < "$SNAPSHOT")
SIZE=$(du -h "$SNAPSHOT" | cut -f1)

echo "[sync-mempalace] записано: $SNAPSHOT ($LINES строк, $SIZE)"

# (Опционально) ре-индексировать в mempalace
if command -v mempalace >/dev/null 2>&1; then
  # Проверка работоспособности с таймаутом
  if timeout 5 mempalace status >/dev/null 2>&1; then
    echo "[sync-mempalace] mempalace работает, переиндексирую source..."
    timeout 30 mempalace mine "$SNAPSHOT" --wing open-finance --mode docs 2>&1 | tail -5 || \
      echo "[sync-mempalace] WARN: re-indexing failed (timeout или ошибка)"
  else
    echo "[sync-mempalace] WARN: mempalace status не отвечает — пропускаю ре-индексацию"
    echo "[sync-mempalace] См. docs/MEMPALACE_RUNBOOK.md для починки"
  fi
fi

echo "[sync-mempalace] DONE"
